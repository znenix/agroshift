// Writes docs/i18n-proofread.md: every UI text in English, Uzbek and Russian, side by side, for the
// native speakers on the team (SPEC §7). Run: node scripts/i18n-proofread.mjs
import { readFileSync, writeFileSync } from "node:fs";

const read = (lang) => JSON.parse(readFileSync(`locales/${lang}.json`, "utf8"));
const en = read("en");
const uz = read("uz");
const ru = read("ru");
const cell = (s) => (s ?? "**MISSING**").replaceAll("|", "\\|").replaceAll("\n", " ");

const GROUP_TITLES = {
  app: "App", a11y: "Accessibility", nav: "Navigation", lang: "Language", common: "Common", landing: "Landing page",
  field: "Field flow", map: "Map (step 1)", point: "Map points", conditions: "Field conditions (step 2)", series: "Chart series",
  trend: "Trends", indicator: "Indicators", unit: "Units", status: "Status", confidence: "Confidence", texture: "Soil texture",
  salinity: "Salinity classes", farm: "Your farm (step 3)", priority: "Priorities", reliability: "Water supply", irrigation: "Irrigation",
  compare: "Compare rotations (step 4)", metric: "Metrics", value: "Values", benefit: "Benefits", risk: "Risks", gap: "Information gaps",
  fit: "Crop fit", satellite: "Satellite check", judgment: "Judgment panel", stress: "Stress test (step 5)", family: "Plant families",
  rotation: "Rotations", crop: "Crop reasons", source: "Sources", about: "About page", glossary: "Glossary", footer: "Footer",
};

const groups = new Map();
for (const key of Object.keys(en)) {
  const g = key.split(".")[0];
  if (!groups.has(g)) groups.set(g, []);
  groups.get(g).push(key);
}

const lines = [
  "# Uzbek and Russian proofreading list",
  "",
  "Generated by `node scripts/i18n-proofread.mjs` from `locales/*.json`. The Uzbek and Russian texts were drafted with AI and **must be proofread by native speakers on the team** (SPEC §7) before the demo.",
  "",
  "**How to fix a text:**",
  "- Edit `locales/uz.json` or `locales/ru.json`, not this file.",
  "- Keep every `{placeholder}` exactly as it is; `npm test` checks this.",
  "- Uzbek must stay in Latin script, with `ʻ` (U+02BB) in oʻ/gʻ and `ʼ` (U+02BC) for the tutuq belgisi.",
  "- Then run this script again.",
  "",
  "**Proofread first** (on screen during the 30-second demo): `field`, `map`, `conditions`, `farm`, `compare`, `satellite`, `stress`, `indicator`, `status`, `confidence`.",
  "",
  "## Terms to confirm",
  "",
  "| English | Oʻzbekcha (draft) | Русский (draft) |",
  "|---|---|---|",
  "| crop rotation | almashlab ekish | севооборот |",
  "| evaporative demand (ET0) | bugʻlanish talabi | испаряемость |",
  "| bare soil | ochiq tuproq | голая почва |",
  "| second crop (after the wheat harvest) | takroriy ekin | повторная культура |",
  "| salinity | shoʻrlanish | засоление |",
  "| confidence (high/medium/low) | ishonchlilik | достоверность |",
  "| what-if test, not a forecast | «agar shunday boʻlsa» sinovi, prognoz emas | проверка «что если», а не прогноз |",
  "| stress test | stress-test | стресс-тест |",
  "| rain-fed (lalmi) | lalmi | богарное (лалми) |",
  "| furrow / sprinkler / drip | egatlab / yomgʻirlatib / tomchilatib | по бороздам / дождевание / капельный |",
  "",
  "## Known issues to check",
  "",
  "- **Soil texture classes** are USDA classes (`texture.*`). Local soil science uses the Kachinsky classification, so the names are approximate. Check that they read sensibly, or switch to a short description.",
  "- **Russian plurals:** `value.days_year`, `unit.*` and `trend.detail` use one form (\"дней\") for every number; `value.seasons` avoids the problem as \"сезонов: {value}\". Rephrase if needed.",
  "- **Russian city phrases:** `field.choose.near` and `conditions.location` say \"рядом с городом {city}\" and \"… км от города {city}\" so that the city name can stay in the nominative case.",
  "",
];

for (const [g, keys] of groups) {
  lines.push(`## ${GROUP_TITLES[g] ?? g} (\`${g}.*\`)`, "", "| Key | English | Oʻzbekcha | Русский |", "|---|---|---|---|");
  for (const k of keys) lines.push(`| \`${k}\` | ${cell(en[k])} | ${cell(uz[k])} | ${cell(ru[k])} |`);
  lines.push("");
}
writeFileSync("docs/i18n-proofread.md", lines.join("\n"));
console.log(`docs/i18n-proofread.md: ${Object.keys(en).length} keys in ${groups.size} groups`);
